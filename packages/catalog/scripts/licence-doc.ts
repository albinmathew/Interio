/**
 * Writes `docs/assets/catalog.md`, the licence record for every model the
 * catalog ships, from `src/models.ts`. Run after changing the model list:
 *
 *   pnpm --filter @interio/catalog licence-doc
 */
import fs from 'node:fs';
import path from 'node:path';
import { CATALOG } from '../src/index';
import { MODELS, PACKS, type ModelSpec, type PackId } from '../src/models';
import { LICENCE_DOC, MODELS_DIR, THUMBS_DIR } from './lib/paths';

const dirSize = (dir: string, ext: string): number =>
  fs.existsSync(dir)
    ? fs
        .readdirSync(dir)
        .filter((f) => f.endsWith(ext))
        .reduce((s, f) => s + fs.statSync(path.join(dir, f)).size, 0)
    : 0;
const mb = (bytes: number) => `${(bytes / 1024 / 1024).toFixed(2)} MB`;

const models = Object.entries(MODELS) as [string, ModelSpec][];
const parametric = CATALOG.filter((e) => e.model.kind === 'parametric');
const lines: string[] = [
  '# Catalog assets and licences',
  '',
  'Generated by `packages/catalog/scripts/licence-doc.ts` from `packages/catalog/src/models.ts`. Do not edit by hand.',
  '',
  'Only CC0-1.0 assets, or models generated by this project, are accepted in the catalog.',
  '',
  '## Shipped payload',
  '',
  '| What | Where | Files | Size |',
  '|---|---|---|---|',
  `| GLB models | \`apps/web/public/catalog/models\` | ${models.length} | ${mb(dirSize(MODELS_DIR, '.glb'))} |`,
  `| Thumbnails (256 px WebP) | \`apps/web/public/catalog/thumbs\` | ${CATALOG.length} | ${mb(dirSize(THUMBS_DIR, '.webp'))} |`,
  '',
  'The source archives are not committed. To rebuild the models, download each pack from its source page, extract it and run',
  '`pnpm --filter @interio/catalog models -- --pack <pack id>=<extracted folder>`, then `pnpm --filter @interio/catalog thumbnails`.',
  '',
  '## Source packs',
  '',
];
for (const [id, pack] of Object.entries(PACKS)) {
  const used = models.filter(([, m]) => m.pack === (id as PackId));
  lines.push(
    `### ${pack.name} ${pack.version} (\`${id}\`)`,
    '',
    `- Author: ${pack.author}`,
    `- Source: ${pack.url}`,
    `- Licence: ${pack.licence} (${pack.licenceUrl})`,
    `- Verification: ${pack.verified}`,
    `- Files used: ${new Set(used.map(([, m]) => m.source)).size} source models, shipped as ${used.length} GLB files`,
    '- Changes made: flattened to one mesh per material, scaled to real-world sizes, origin moved to the bottom centre, recoloured with the catalog palette, texture coordinates dropped. Some source models ship in several sizes or finishes.',
    '',
    '| Shipped file | Source file | Size (w x d x h, mm) |',
    '|---|---|---|',
    ...used.map(([file, m]) => `| \`${file}.glb\` | \`${m.source}.glb\` | ${m.dims.w} x ${m.dims.d} x ${m.dims.h} |`),
    '',
  );
}
lines.push(
  '## Packs considered and not used',
  '',
  '| Pack | Decision |',
  '|---|---|',
  '| Quaternius furniture packs (quaternius.com) | Not downloaded. The Kenney kit plus parametric generators cover every required piece, and a second kit would mix shading styles. |',
  '| KayKit Furniture Bits (kaylousberg.itch.io) | Not downloaded, for the same reason. |',
  '',
  '## Parametric models',
  '',
  `${parametric.length} entries are generated in code by \`packages/catalog/src/generators\` (authored for this project, no third-party geometry).`,
  'They are offered under CC0-1.0 like the rest of the catalog content.',
  '',
  '| Generator | Entries |',
  '|---|---|',
);
const byGenerator = new Map<string, string[]>();
for (const e of parametric) {
  if (e.model.kind !== 'parametric') continue;
  byGenerator.set(e.model.generator, [...(byGenerator.get(e.model.generator) ?? []), e.id]);
}
for (const [generator, ids] of [...byGenerator.entries()].sort(([a], [b]) => a.localeCompare(b))) lines.push(`| \`${generator}\` | ${ids.map((i) => `\`${i}\``).join(', ')} |`);
lines.push('');

fs.mkdirSync(path.dirname(LICENCE_DOC), { recursive: true });
fs.writeFileSync(LICENCE_DOC, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), LICENCE_DOC)}`);
